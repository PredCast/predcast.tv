import { z } from 'zod';

import { DoubleXpSourceSchema, RankTierSchema } from '../gamification/GamificationEnums';

const REASON = z.string().trim().min(3).max(280);

// ─── Double XP (§3.6) ─────────────────────────────────────────────────────────

export const AdminDoubleXpStatusSchema = z.enum(['upcoming', 'running', 'ended', 'cancelled']);

export const AdminDoubleXpEventDtoSchema = z.object({
    id: z.string(),
    name: z.string(),
    multiplier: z.number(),
    sources: z.array(DoubleXpSourceSchema),
    startsAt: z.string(),
    endsAt: z.string(),
    status: AdminDoubleXpStatusSchema,
    createdByWallet: z.string(),
    createdAt: z.string(),
    cancelledAt: z.string().nullable(),
    cancelledByWallet: z.string().nullable(),
});

/** Guards of §3.6, read from the domain catalog so the form never hardcodes them. */
export const AdminDoubleXpRulesDtoSchema = z.object({
    eligibleSources: z.array(DoubleXpSourceSchema),
    multipliers: z.array(z.number()),
    minNoticeHours: z.number().int(),
    maxDurationHours: z.number().int(),
    maxPerMonth: z.number().int(),
    announceDays: z.number().int(),
    /** False when the legal switch turns double XP off: creation is refused. */
    enabled: z.boolean(),
});

export const AdminDoubleXpMonthUsageDtoSchema = z.object({
    /** Paris `YYYY-MM`. */
    month: z.string(),
    used: z.number().int(),
    limit: z.number().int(),
});

export const AdminDoubleXpListDtoSchema = z.object({
    items: z.array(AdminDoubleXpEventDtoSchema),
    rules: AdminDoubleXpRulesDtoSchema,
    monthlyUsage: z.array(AdminDoubleXpMonthUsageDtoSchema),
});

export const AdminDoubleXpListQuerySchema = z.object({
    limit: z.coerce.number().int().min(1).max(100).default(50),
});

export const AdminCreateDoubleXpBodySchema = z.object({
    name: z.string().trim().min(3).max(80),
    multiplier: z.number().gt(1).lte(2).multipleOf(0.25),
    sources: z.array(DoubleXpSourceSchema).min(1).default(['check_in', 'watch', 'chat_message', 'stream_time']),
    startsAt: z.string().datetime(),
    endsAt: z.string().datetime(),
});

export const AdminCancelDoubleXpBodySchema = z.object({ note: REASON });

// ─── Account (suspension, adjustment, player block) ──────────────────────────

export const AdminGamificationReasonBodySchema = z.object({ reason: REASON });

export const AdminSuspensionDtoSchema = z.object({ suspendedAt: z.string().nullable() });

export const AdminAdjustXpBodySchema = z.object({
    /** Signed; a negative adjustment never takes the total below 0. */
    xp: z.number().int().min(-100_000).max(100_000).refine((v) => v !== 0, 'xp must not be 0'),
    note: REASON,
    /** Idempotency key generated by the form: a retried submit credits once. */
    adjustmentId: z.string().uuid(),
});

export const AdminAdjustXpResultDtoSchema = z.object({
    status: z.enum(['credited', 'duplicate']),
    /** XP actually written (a negative one may be bounded by the total). */
    xp: z.number().int().nullable(),
    ledgerId: z.number().int().nullable(),
});

export const AdminLedgerEntryDtoSchema = z.object({
    id: z.number().int(),
    source: z.string(),
    xp: z.number().int(),
    requestedXp: z.number().int(),
    baseXp: z.number().int(),
    multiplier: z.number(),
    reason: z.string().nullable(),
    refKey: z.string(),
    day: z.string(),
    occurredAt: z.string(),
    reversesId: z.number().int().nullable(),
    /** Adjustment note (admin_adjustment only). */
    note: z.string().nullable(),
});

export const AdminGamificationStateSchema = z.enum(['live', 'disabled', 'not_launched']);

export const AdminAccountGamificationDtoSchema = z.object({
    wallet: z.string(),
    state: AdminGamificationStateSchema,
    /** Null when no account is linked to the wallet (never signed in with Dynamic). */
    account: z
        .object({
            accountId: z.string(),
            createdAt: z.string(),
            linkedWallets: z.array(z.string()),
            /** False before the first credit: the figures are the level-1 defaults. */
            hasProfile: z.boolean(),
            xpTotal: z.number().int(),
            level: z.number().int(),
            levelPeak: z.number().int(),
            rankTier: RankTierSchema,
            levelStart: z.number().int(),
            nextLevelAt: z.number().int().nullable(),
            streak: z.object({
                current: z.number().int(),
                best: z.number().int(),
                alive: z.boolean(),
                freezes: z.number().int(),
                lastDay: z.string().nullable(),
            }),
            suspendedAt: z.string().nullable(),
            suspendedReason: z.string().nullable(),
            recentLedger: z.array(AdminLedgerEntryDtoSchema),
        })
        .nullable(),
});

export type AdminDoubleXpStatus = z.infer<typeof AdminDoubleXpStatusSchema>;
export type AdminDoubleXpEventDto = z.infer<typeof AdminDoubleXpEventDtoSchema>;
export type AdminDoubleXpRulesDto = z.infer<typeof AdminDoubleXpRulesDtoSchema>;
export type AdminDoubleXpMonthUsageDto = z.infer<typeof AdminDoubleXpMonthUsageDtoSchema>;
export type AdminDoubleXpListDto = z.infer<typeof AdminDoubleXpListDtoSchema>;
export type AdminCreateDoubleXpBody = z.infer<typeof AdminCreateDoubleXpBodySchema>;
export type AdminCreateDoubleXpInput = z.input<typeof AdminCreateDoubleXpBodySchema>;
export type AdminCancelDoubleXpBody = z.infer<typeof AdminCancelDoubleXpBodySchema>;
export type AdminGamificationReasonBody = z.infer<typeof AdminGamificationReasonBodySchema>;
export type AdminSuspensionDto = z.infer<typeof AdminSuspensionDtoSchema>;
export type AdminAdjustXpBody = z.infer<typeof AdminAdjustXpBodySchema>;
export type AdminAdjustXpResultDto = z.infer<typeof AdminAdjustXpResultDtoSchema>;
export type AdminLedgerEntryDto = z.infer<typeof AdminLedgerEntryDtoSchema>;
export type AdminGamificationState = z.infer<typeof AdminGamificationStateSchema>;
export type AdminAccountGamificationDto = z.infer<typeof AdminAccountGamificationDtoSchema>;
